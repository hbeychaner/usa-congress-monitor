import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');

test('generation is deterministic, stale checks fail without writing, and exporter failures propagate', () => {
    const root = mkdtempSync(join(tmpdir(), 'congress-contracts-'));
    try {
        const scripts = join(root, 'frontend/app/scripts');
        const target = join(root, 'frontend/app/src/shared/contracts/api.ts');
        const bin = join(root, 'bin');
        mkdirSync(scripts, { recursive: true });
        mkdirSync(dirname(target), { recursive: true });
        mkdirSync(bin);
        symlinkSync(join(app, 'node_modules'), join(root, 'frontend/app/node_modules'), 'dir');
        const generator = join(scripts, 'generate-contracts.mjs');
        writeFileSync(generator, readFileSync(join(app, 'scripts/generate-contracts.mjs')));
        const schema = JSON.stringify({
            openapi: '3.1.0', info: { title: 'Fixture', version: '1' },
            components: { schemas: { FixtureRecord: {
                type: 'object', additionalProperties: false,
                properties: {
                    id: { type: 'string', readOnly: true },
                    label: { anyOf: [{ type: 'string' }, { type: 'null' }] },
                    options: { type: 'array', items: { type: 'string' }, default: [] },
                    state: { type: 'string', enum: ['open', 'closed'] },
                },
                required: ['id', 'label', 'options', 'state'],
            } } },
            paths: { '/fixture': { get: {
                operationId: 'fixture',
                parameters: [{ name: 'state', in: 'query', schema: { type: 'string', enum: ['open', 'closed'] } }],
                responses: { '200': {
                    description: 'Fixture response',
                    content: { 'application/json': { schema: { $ref: '#/components/schemas/FixtureRecord' } } },
                } },
            } } },
        });
        const uv = join(bin, 'uv');
        writeFileSync(uv, `#!/bin/sh\nprintf '%s\\n' '${schema}'\n`, { mode: 0o755 });
        const env = { ...process.env, PATH: `${bin}:${process.env.PATH}` };
        const run = (...args) => spawnSync(process.execPath, [generator, ...args], { env, encoding: 'utf8' });

        assert.equal(run('--check').status, 1);
        assert.equal(run().status, 0);
        const generated = readFileSync(target, 'utf8');
        assert.match(generated, /auto-generated by @hey-api\/openapi-ts/);
        assert.equal(run('--check').status, 0);
        assert.equal(run().status, 0);
        assert.equal(readFileSync(target, 'utf8'), generated);
        const checks = join(root, 'assertions.ts');
        writeFileSync(checks, `
import type { FixtureRecord, FixtureData, FixtureResponses } from './frontend/app/src/shared/contracts/api';
const valid: FixtureRecord = { id: 'one', label: null, options: [], state: 'open' };
const response: FixtureResponses[200] = valid;
const query: FixtureData['query'] = { state: 'closed' };
// @ts-expect-error Defaults remain required when the response schema requires them.
const missing: FixtureRecord = { id: 'one', label: null, state: 'open' };
// @ts-expect-error Nullable strings do not accept numbers.
const wrongLabel: FixtureRecord = { ...valid, label: 1 };
// @ts-expect-error Schema enums remain closed.
const wrongState: FixtureRecord = { ...valid, state: 'unknown' };
// @ts-expect-error Operation query enums remain closed.
const wrongQuery: FixtureData['query'] = { state: 'unknown' };
// @ts-expect-error Read-only response fields remain read-only.
valid.id = 'two';
`);
        const program = ts.createProgram([checks], {
            strict: true, noEmit: true, skipLibCheck: true, types: [],
            target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext,
            moduleResolution: ts.ModuleResolutionKind.Bundler,
        });
        assert.deepEqual(ts.getPreEmitDiagnostics(program).map(diagnostic =>
            ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n')), []);
        writeFileSync(target, `${generated}\n// stale\n`);
        const stale = readFileSync(target, 'utf8');
        const check = run('--check');
        assert.equal(check.status, 1);
        assert.match(check.stderr, /contracts are stale/);
        assert.equal(readFileSync(target, 'utf8'), stale);
        writeFileSync(uv, '#!/bin/sh\nexit 7\n');
        assert.notEqual(run().status, 0);
        assert.equal(readFileSync(target, 'utf8'), stale);
        writeFileSync(uv, "#!/bin/sh\nprintf '%s\\n' 'not-json'\n");
        assert.notEqual(run().status, 0);
        assert.equal(readFileSync(target, 'utf8'), stale);
    } finally {
        rmSync(root, { recursive: true });
    }
});

test('wrappers retain URL encoding, repeated filters, null omission, and request methods', async () => {
    const root = mkdtempSync(join(tmpdir(), 'congress-api-wrappers-'));
    try {
        writeFileSync(join(root, 'client.mjs'),
            'export const apiGet = path => ({path, method: "GET"});\n' +
            'export const apiPost = path => ({path, method: "POST"});\n');
        const load = async (name) => {
            const source = readFileSync(join(app, `src/api/${name}.ts`), 'utf8');
            const output = ts.transpileModule(source, {
                compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 },
            }).outputText.replaceAll("from './client'", "from './client.mjs'");
            const file = join(root, `${name}.mjs`);
            writeFileSync(file, output);
            return import(pathToFileURL(file).href);
        };
        const bills = await load('bills');
        assert.equal(bills.fetchBill('bill:119/hr 1').path, '/api/v1/bills/bill%3A119%2Fhr%201');
        const recent = new URL(bills.fetchRecentBills(50, 2, {
            query: 'health & care', congress: '119', chamber: 'House',
            billType: 'hr', subject: 'Policy & law', hasVotes: true,
        }).path, 'http://fixture');
        assert.deepEqual(Object.fromEntries(recent.searchParams), {
            limit: '50', page: '2', query: 'health & care', congress: '119',
            chamber: 'House', bill_type: 'hr', subject: 'Policy & law', has_votes: 'true',
        });
        const graph = await load('graph');
        const query = new URL(graph.fetchNeighborhood({
            members: ['A', 'B'], parties: ['democratic', 'republican'],
            collaborationWeight: 1, votingWeight: 0.6, topicWeight: 0.3,
            congress: null, chamber: null, limit: 15,
            includeTopics: false, includeSubjects: true, includeMetasubjects: false,
        }).path, 'http://fixture').searchParams;
        assert.deepEqual(query.getAll('member'), ['A', 'B']);
        assert.deepEqual(query.getAll('party'), ['democratic', 'republican']);
        assert.equal(query.has('congress'), false);
        assert.equal(query.has('chamber'), false);
        assert.equal(query.get('include_topics'), 'false');
        const admin = await load('admin');
        assert.equal(admin.fetchTopicTraining().method, 'GET');
        assert.equal(admin.startTopicTraining().method, 'POST');
    } finally {
        rmSync(root, { recursive: true });
    }
});
